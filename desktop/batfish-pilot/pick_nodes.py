"""Pick a connected set of nodes for the Batfish pilot from your backend's IS-IS topology API.

Read-only. Usage:
  export BACKEND_URL=http://<backend-host>:4000
  python pick_nodes.py path   <SRC_NAME> <DST_NAME>   # shortest IS-IS path + 1-hop neighbours of each node
  python pick_nodes.py around <NAME> <HOPS>           # everything within N hops of a node

Uses GET /isis-adjacency/topology  ->  { nodes: [{id(name), ip}], links: [{source, target, metric, state, ...}] }
Writes nodes.txt (overwrites).
"""
import os
import sys
import requests
import networkx as nx

BASE = os.environ["BACKEND_URL"].rstrip("/")
resp = requests.get(f"{BASE}/isis-adjacency/topology", timeout=30)
resp.raise_for_status()
data = resp.json()


def norm(n):
    # neighbor names can be FQDNs (x.liquidtelecom.net); device names are short.
    return str(n).split(".")[0].strip().lower()


ips = {norm(n["id"]): n.get("ip") for n in data["nodes"]}

G = nx.Graph()
for l in data["links"]:
    if l.get("state") != "Up":
        continue
    a, b = norm(l["source"]), norm(l["target"])
    w = l["metric"] if l.get("metric") is not None else 1
    # two rows describe one physical link (one per side); keep the lowest metric
    if not G.has_edge(a, b) or G[a][b]["metric"] > w:
        G.add_edge(a, b, metric=w)

print(f"Graph: {G.number_of_nodes()} nodes, {G.number_of_edges()} up adjacencies")

mode = sys.argv[1] if len(sys.argv) > 1 else ""
if mode == "path":
    src, dst = norm(sys.argv[2]), norm(sys.argv[3])
    path = nx.shortest_path(G, src, dst, weight="metric")
    cost = nx.shortest_path_length(G, src, dst, weight="metric")
    print(f"Shortest path (metric {cost}): " + " -> ".join(path))
    chosen = set(path)
    for n in path:  # direct neighbours, so Batfish sees both ends of every link
        chosen.update(G.neighbors(n))
elif mode == "around":
    chosen = set(nx.ego_graph(G, norm(sys.argv[2]), radius=int(sys.argv[3])).nodes)
else:
    sys.exit(__doc__)

names = sorted(chosen)
print(f"\n{len(names)} nodes selected" + ("  (large: use fewer hops)" if len(names) > 25 else ""))
for n in names:
    print(f"  {n.upper():28} {ips.get(n) or '(no ip: not in the nodes list)'}")

out = os.path.join(os.path.dirname(__file__), "nodes.txt")
with open(out, "w") as f:
    f.write("# generated by pick_nodes.py\n")
    f.write("\n".join(n.upper() for n in names) + "\n")
print(f"\nWrote {out}")
